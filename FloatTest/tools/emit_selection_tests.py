def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "case",
        choices=("CS_Ctrl_Att_Rate", "CS_IRES_Attitude", "CS_Track_Atti"),
    )
    case = parser.parse_args().case
    {
        "CS_Ctrl_Att_Rate": emit_ctrl,
        "CS_IRES_Attitude": emit_ires,
        "CS_Track_Atti": emit_track,
    }[case]()


if __name__ == "__main__":
    main()
